"""Assign a family to each HERCULES.FS entry (by magic, size, name extension) and document it.

Inputs: manifests/archive-manifest.json and manifests/fs-index-report.json.
Outputs: manifests/archive-families.json ({index: family}) and docs/archive-format.md.
Families are container labels only; field layouts come from Ghidra/runtime work (P2/P4).
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
I_MAGIC = re.compile(rb"^i\d\.[0-9a-z]$")

# family -> (rule description, where the format comes from / status)
FAMILIES = {
    "esf_audio": ("magic `ESF\\x03`, `.ESF`", "header per CTPAX `esftowav.c` (FACTS); confirm reader in Ghidra (P2/P4)"),
    "tga_cmap": ("magic `00 01 01 00`, `.TGA`", "colour-mapped TGA, all 320x256 8 bpp, descriptor byte 0x11 = 0 (raw; CTPAX sets bit 5 on extract)"),
    "anim_bin": ("`ANIMPSX.BIN`", "unknown; most start `i1.4`"),
    "map_bin": ("`MAP_PSX.BIN`", "unknown; `i2.5` or `i1.a`"),
    "map_cif": ("`MAP_PSX.CIF`", "unknown; all 336,384 bytes"),
    "sonix_sfx": ("`.SFX`", "unknown; all 452 bytes"),
    "sonix_mus": ("`.MUS`", "unknown; all 452 bytes"),
    "demo_dat": ("`DEMO*.DAT`", "unknown; all 4,096 bytes"),
    "lang_dat": ("`LANGUAGE\\SRCLANG\\*.DAT`", "unknown"),
    "icontainer_unnamed": ("no name, magic `i<d>.<c>`", "same magic family as anim_bin/map_bin; name unknown"),
    "unknown": ("anything else", "unknown"),
}


def family(row: dict) -> str:
    magic = bytes.fromhex(row["magic"] or "")
    name = row["name_candidate"] or ""
    base = name.rsplit("\\", 1)[-1]
    ext = row["extension"]
    if magic == b"ESF\x03":
        return "esf_audio"
    if ext == "TGA" and magic == b"\x00\x01\x01\x00":
        return "tga_cmap"
    if base == "ANIMPSX.BIN":
        return "anim_bin"
    if base == "MAP_PSX.BIN":
        return "map_bin"
    if base == "MAP_PSX.CIF":
        return "map_cif"
    if ext == "SFX":
        return "sonix_sfx"
    if ext == "MUS":
        return "sonix_mus"
    if ext == "DAT":
        return "demo_dat" if base.startswith("DEMO") else "lang_dat"
    if not name and I_MAGIC.match(magic):
        return "icontainer_unnamed"
    return "unknown"


def fmt_magic(h: str) -> str:
    b = bytes.fromhex(h)
    return f"`{b.decode('latin-1')}`" if all(0x20 <= c < 0x7F for c in b) else f"`{h}`"


def render(entries: list[dict], fam: dict[int, str], report: dict) -> str:
    by_fam = defaultdict(list)
    for r in entries:
        if r["size"]:
            by_fam[fam[r["index"]]].append(r)
    lines = [
        "# HERCULES.FS archive format",
        "",
        "Generated by `tools/fs/classify.py` from `manifests/archive-manifest.json`. Family layouts are not decoded here.",
        "",
        "## Container",
        "",
        f"- Size {report['archive_size']:,} bytes. Index at offset 0: 1,024 records x 12 bytes (`u32 id, u32 offset, u32 size`, LE) = 0x3000 bytes.",
        f"- {report['nonempty']} non-empty entries; payloads start at 0x3000 and end at {report['payload_end']:#x} "
        f"(overlaps {len(report['overlaps'])}, gaps {len(report['gaps'])}, trailing bytes {report['trailing_bytes']}).",
        f"- {len(report['zero_size'])} zero-size records: {len(report['zero_id_indices'])} zero-id tail records from index "
        f"{report['zero_id_indices'][0]}, plus "
        + ", ".join(f"index {z['index']} (id {z['id']})" for z in report["zero_size"] if z["id"] != "00000000") + ".",
        f"- Duplicate ids: {len(report['duplicate_ids'])}. Identical payload groups: {len(report['identical_payload_groups'])} "
        f"({sum(len(g) for g in report['identical_payload_groups'])} entries).",
        "- Record order is not offset order.",
        "- Ids are the CTPAX name hash `sum(toupper(c) << ((i&3)*8)) + strlen` over full `M:\\...` paths "
        "(`tools/fs/resource_hash.py`; the game's own hash routine is a P2 task).",
        "",
        "## Families",
        "",
        "| family | rule | entries | bytes | sizes | magics | status |",
        "|---|---|---:|---:|---|---|---|",
    ]
    for f, (rule, status) in FAMILIES.items():
        rows = by_fam.get(f, [])
        if not rows:
            continue
        sizes = sorted({r["size"] for r in rows})
        size_txt = f"{sizes[0]:,}" if len(sizes) == 1 else f"{sizes[0]:,}–{sizes[-1]:,} ({len(sizes)} distinct)"
        magics = Counter(r["magic"] for r in rows)
        mtxt = ", ".join(f"{fmt_magic(m)} {n}" for m, n in magics.most_common(4))
        if len(magics) > 4:
            mtxt += f", +{len(magics) - 4} more"
        lines.append(f"| {f} | {rule} | {len(rows)} | {sum(r['size'] for r in rows):,} | {size_txt} | {mtxt} | {status} |")
    unnamed = [r for r in entries if r["size"] and not r["name_candidate"]]
    lines += [
        "",
        f"## Unnamed entries ({len(unnamed)})",
        "",
        "| index | id | size | magic | family |",
        "|---:|---|---:|---|---|",
    ]
    lines += [f"| {r['index']} | {r['id']} | {r['size']:,} | {fmt_magic(r['magic'])} | {fam[r['index']]} |" for r in unnamed]
    lines += ["", "## Identical payload groups", "", "| indices | family | size |", "|---|---|---:|"]
    idx = {r["index"]: r for r in entries}
    for g in sorted(report["identical_payload_groups"]):
        lines.append(f"| {', '.join(map(str, g))} | {fam[g[0]]} | {idx[g[0]]['size']:,} |")
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--manifest", type=Path, default=ROOT / "manifests" / "archive-manifest.json")
    ap.add_argument("--report", type=Path, default=ROOT / "manifests" / "fs-index-report.json")
    ap.add_argument("--families", type=Path, default=ROOT / "manifests" / "archive-families.json")
    ap.add_argument("--doc", type=Path, default=ROOT / "docs" / "archive-format.md")
    a = ap.parse_args(argv)
    entries = json.loads(a.manifest.read_text(encoding="utf-8"))["entries"]
    report = json.loads(a.report.read_text(encoding="utf-8"))
    fam = {r["index"]: family(r) for r in entries}
    a.families.write_text(json.dumps({str(k): v for k, v in fam.items()}, indent=1), encoding="utf-8")
    a.doc.write_text(render(entries, fam, report), encoding="utf-8")
    counts = Counter(fam[r["index"]] for r in entries if r["size"])
    print(" ".join(f"{k}={v}" for k, v in counts.most_common()) + f" -> {a.families.name}, {a.doc}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
