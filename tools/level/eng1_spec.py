"""Generated object tables for the ENG1 level specs (L*.GP.03/04) -> docs/full-game/levels/<Lxx>.md.

    eng1_spec.py [SLUG ...]   (default: L03 L04 L05 L06 L08 L10)

Fills the block between <!-- objects:begin --> and <!-- objects:end --> (appended if missing) from
extracted/meta/full-game/<SLUG>-types.json (kinds, class, counts, banks, handlers, category LEAD) and
<SLUG>-enemies.json (tools/level/enemy_digest.py: hero damage per HERO_RequestDamage n through the ENG1 table
0x55348 with index n & 7, hit points, hittable, difficulty reads, sounds). Everything outside the block is
hand-written and kept.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
META = ROOT / "extracted" / "meta" / "full-game"
DOCS = ROOT / "docs" / "full-game" / "levels"
BEGIN, END = "<!-- objects:begin -->", "<!-- objects:end -->"
GROUPS = [("Enemies and bosses", ("enemy_animation", "boss_animation")),
          ("NPCs and rescues", ("npc_animation",)),
          ("Hazards and effects", ("fx_projectiles", "chase_hazards", "flight_animation")),
          ("Pickups, markers and props", ("props_pickups",)),
          ("Other kinds", None)]


def rows(slug: str) -> str:
    t = json.loads((META / f"{slug}-types.json").read_text(encoding="utf-8"))
    e = {k["kind"]: k for k in json.loads((META / f"{slug}-enemies.json").read_text(encoding="utf-8"))["kinds"]}
    used = set()
    out = [BEGIN, f"## Objects (generated by `tools/level/eng1_spec.py`)", "",
           f"Source: `extracted/meta/full-game/{slug}-types.json` (map and code-spawned kinds; class = kind & 0x7000) and "
           f"`{slug}-enemies.json`. Damage is the hero damage per hit (Beginner/Medium/Herculean) for each "
           "`HERO_RequestDamage(obj, n)` constant in the handlers: table 0x55348, index n & 7 (`encounters.md`, index rule). "
           "Categories are a LEAD rule (class + bank path). Placed = map spawns (0 = spawned by code).", ""]
    for title, cats in GROUPS:
        sel = [k for k in t["kinds"] if k["kind"] not in used and (cats is None or k.get("category") in cats)]
        if not sel:
            continue
        out += [f"### {title}", "", "| kind | class | placed | bank | handlers (spawn / update) | damage B/M/H | HP | hittable | diff. reads | sounds |",
                "|---|---|---:|---|---|---|---|---|---:|---|"]
        for k in sorted(sel, key=lambda k: int(k["kind"], 16)):
            used.add(k["kind"])
            d = e.get(k["kind"], {})
            ent = k.get("entry") or {}
            names = " / ".join(f"{(ent.get(r) or {}).get('name') or '-'} {(ent.get(r) or {}).get('rva') or ''}".strip()
                               for r in ("spawn", "update") if r in ent) or ("init/tick: " + ", ".join(
                f"{v.get('name')} {v.get('rva')}" for v in ent.values() if isinstance(v, dict)) if ent else "–")
            dmg = "; ".join("/".join(map(str, h["damage_beginner_medium_herculean"])) + f" (n={h['strength']:#x})"
                            for h in d.get("hits", [])) or "–"
            hp = ", ".join(map(str, d.get("hp_constants", []))) or ("difficulty·2 + 6" if d.get("enemy_init_hp") else "–")
            bank = ((k.get("bank") or {}).get("path") or "–").replace("P:\\SRC1\\", "")
            out.append(f"| {k['kind']} | {k.get('class')} | {k.get('count') or 0} | {bank} | {names} | {dmg} | {hp} | "
                       f"{'yes' if d.get('can_be_hit') else '–'} | {d.get('difficulty_reads', 0)} | {', '.join(d.get('sounds', [])) or '–'} |")
        out.append("")
    out.append(END)
    return "\n".join(out)


def main(argv: list[str]) -> int:
    for slug in argv[1:] or ["L03", "L04", "L05", "L06", "L08", "L10"]:
        doc = next(iter(DOCS.glob(f"{slug}.md")), None)
        if doc is None:
            print(slug, "no doc yet, skipped")
            continue
        s = doc.read_text(encoding="utf-8")
        block = rows(slug)
        if BEGIN in s and END in s:
            s = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, s, flags=re.S)
        else:
            s = s.rstrip("\n") + "\n\n" + block + "\n"
        doc.write_text(s, encoding="utf-8")
        print(slug, "->", doc.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
