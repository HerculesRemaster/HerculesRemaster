"""Write docs/full-game/gameplay/actor-digest.md from extracted/meta/full-game/L*-enemies.json + L*-types.json.

One table per ENG1 level: every actor kind with handlers, its bank, scene category (LEAD rule), handler names,
hero damage per hit strength (Beginner/Medium/Herculean, ENG1 0x55348), hit points, whether it can be hit,
difficulty reads and sounds. All columns are static extractions (tools/level/enemy_digest.py); the per-encounter
behaviour is in encounters.md.

    actor_digest_doc.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
META = ROOT / "extracted" / "meta" / "full-game"


def main() -> int:
    out = ["# Actor digest per ENG1 level (static)", "",
           "Generated by `tools/level/actor_digest_doc.py` from `tools/level/enemy_digest.py` and `tools/level/level_types.py`.",
           "",
           "- **Damage:** hero damage per hit, taken from `HERO_RequestDamage(obj, N)` constants in the handlers through the ENG1 table 0x55348, index = N & 7 (RequestDamage stores N + 1, `HERO_ApplyDamage` 0x18c50 indexes (stored − 1) & 7; corrected 2026-10-12).",
           "- **HP:** constants written to +0xee (hit points). \"init\" means `HERO_EnemyInitHp` (difficulty·2 + 6).",
           "- **Category:** a naming rule, LEAD.",
           "- **Evidence:** VERIFIED-STATIC for every column except category.", ""]
    for f in sorted(META.glob("L*-enemies.json")):
        e = json.loads(f.read_text(encoding="utf-8"))
        t = json.loads((META / f.name.replace("-enemies", "-types")).read_text(encoding="utf-8"))
        cat = {k["kind"]: k.get("category") for k in t["kinds"]}
        out += [f"## {f.name[:3]} {e['level']['dir']}", "",
                "| kind | count | bank | category | handlers | damage B/M/H | HP | hittable | diff. reads | sounds |",
                "|---|---:|---|---|---|---|---|---|---:|---|"]
        for k in e["kinds"]:
            dmg = "; ".join("/".join(map(str, h["damage_beginner_medium_herculean"])) for h in k["hits"]) or "–"
            hp = ", ".join(map(str, k["hp_constants"])) + (" init" if k["enemy_init_hp"] else "") or "–"
            bank = (k["bank"] or "–").replace("P:\\SRC1\\", "")
            names = " / ".join(v or "?" for v in k["handlers"].values())
            out.append(f"| {k['kind']} | {k['count']} | {bank} | {cat.get(k['kind']) or '–'} | {names} | {dmg} | {hp or '–'} | "
                       f"{'yes' if k['can_be_hit'] else '–'} | {k['difficulty_reads']} | {', '.join(k['sounds']) or '–'} |")
        out.append("")
    (ROOT / "docs" / "full-game" / "gameplay" / "actor-digest.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("ok")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
