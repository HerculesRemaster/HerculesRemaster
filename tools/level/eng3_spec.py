"""Generated object sections of docs/full-game/levels/{L02,L07,L09}.md (L*.GP.03-05).

    eng3_spec.py
Reads extracted/meta/full-game/L*-types.json (tools/level/eng3_types.py: handlers, bank, map count, category,
identification from analysis/exports/full-game/eng3_kind_handlers.json / eng3_cyclops.json) and rewrites the
block between "<!-- objects:begin -->" and "<!-- objects:end -->" (appended when missing):
  Hazards (GP.03)        category chase_hazards / fx_projectiles with damage
  Enemies (GP.04)        enemy_animation / boss_animation / npc_animation
  Scripts (GP.05)        props_pickups / checkpoint_state / collision_camera and the shared completion rule
Each row: kind, map count (tracks), what, damage (hit code -> HERO_ApplyDamage table 0x380a0 columns), handlers.
Evidence column: VERIFIED-STATIC / VISUAL / LEAD grades the naming only; behaviour is from the decompilation.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LEVELS = {"L02": "GAUNTLET", "L07": "CYCLOPS", "L09": "TORMENT"}
GROUPS = [("Hazards (GP.03)", {"chase_hazards", "fx_projectiles"}),
          ("Enemies, NPCs and bosses (GP.04)", {"enemy_animation", "boss_animation", "npc_animation"}),
          ("Pickups, checkpoints and markers (GP.05)", {"props_pickups", "checkpoint_state", "collision_camera"})]


def cell(s, n=240):
    s = (s or "").replace("|", "/").replace("\n", " ")
    return s if len(s) <= n else s[:n - 1] + "…"


def section(slug):
    d = json.loads((ROOT / "extracted/meta/full-game" / f"{slug}-types.json").read_text(encoding="utf-8"))
    kinds = [k for k in d["kinds"] if k.get("map") or k.get("runtime")]
    out = ["<!-- objects:begin -->", "## Objects (generated by `tools/level/eng3_spec.py`)", "",
           f"Source: `extracted/meta/full-game/{slug}-types.json`. Damage: `HERO_Hit` 0x19200 → `HERO_ApplyDamage` 0x19410, "
           "table 0x380a0 (T0–T4 per difficulty, `docs/full-game/gameplay/chase.md`). No ENG3 object handler reads "
           "the difficulty (gs+0xe); it acts only through that table.", ""]
    for title, cats in GROUPS:
        rows = [k for k in kinds if k.get("category") in cats]
        if not rows:
            continue
        out += [f"### {title}", "", "| kind | placed (tracks) | what | evidence | damage / effect | handlers |", "|---|---|---|---|---|---|"]
        for k in sorted(rows, key=lambda r: int(r["kind"], 16)):
            m = k.get("map")
            placed = f"{m['count']} ({','.join(map(str, m['tracks']))})" if m else "code / runtime"
            eff = k.get("damage") or k.get("gives") or ""
            h = ", ".join(f"{v['name'] or v['rva']}" for r, v in k["entry"].items() if r != "stub" and v["rva"] != "0x2390")
            out.append(f"| {k['kind']} | {placed} | {cell(k.get('what'))} | {k.get('evidence') or '-'} | {cell(eff, 200)} | {h} |")
        out.append("")
    rest = [k for k in kinds if not k.get("category")]
    if rest:
        out += ["Unclassified (child objects; see the types file): " + ", ".join(k["kind"] for k in rest), ""]
    out += ["### Completion (GP.05)", "",
            "The shared end object (`LVL_EndObjectUpdate` 0x16320) starts the ride (state 10). At the level's completion x, "
            "`HERO_LevelComplete` 0x19c20 → state 9 → gs+3 = 0x31 → TITLE tally → gs[0] + 1 (`progression.md`). "
            "Respawn: `HERO_Die` 0x19a30 → gs+1 = gs+2 (restart section set by the Pegasus checkpoints), one life lost "
            "unless gs+0x30 & 8.", "", "<!-- objects:end -->"]
    return "\n".join(out)


def main():
    for slug in LEVELS:
        p = ROOT / "docs/full-game/levels" / f"{slug}.md"
        s = p.read_text(encoding="utf-8")
        new = section(slug)
        if "<!-- objects:begin -->" in s:
            s = re.sub(r"<!-- objects:begin -->.*?<!-- objects:end -->", lambda _: new, s, flags=re.S)
        else:
            s = s.rstrip("\n") + "\n\n" + new + "\n"
        p.write_text(s, encoding="utf-8")
        print(f"{slug}: objects section written -> {p.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
