#define BUFFSIZE 0xFFF
#define LZSS_GETBYTE(p, sz, cr) ((cr < sz) ? p[cr++] : -1)
#define LZSS_PUTBYTE(u, sz, cr, b) ((cr < sz) ? (u[cr++] = b) | 0xff : 0)

void lzss_unpack(uint8_t *p, uint8_t *u, uint32_t ps, uint32_t us) {
uint8_t buff[BUFFSIZE + 1];
int i, j, len, m, b;
uint32_t pi, ui;
  memset(buff, 32, BUFFSIZE + 1);
  i = (BUFFSIZE + 1) - 16;
  pi = 0;
  ui = 0;
  while ((pi < ps) && (ui < us)) {
    b = LZSS_GETBYTE(p, ps, pi);
    if (b == -1) { break; }
    for (m = 0; m < 8; m++) {
      if (!(b & 1)) {
        j = LZSS_GETBYTE(p, ps, pi);
        if (j == -1) { break; }
        len = LZSS_GETBYTE(p, ps, pi);
        if (len == -1) { break; }
        j += ((len & 0xF0) << 4);
        len = (len & 0x0F) + 3;
        while (len > 0) {
          buff[i] = buff[j];
          if (!LZSS_PUTBYTE(u, us, ui, buff[i])) { break; }
          j = (j + 1) & BUFFSIZE;
          i = (i + 1) & BUFFSIZE;
          len--;
        }
      } else {
        j = LZSS_GETBYTE(p, ps, pi);
        if (j == -1) { break; }
        buff[i] = j;
        if (!LZSS_PUTBYTE(u, us, ui, buff[i])) { break; }
        i = (i + 1) & BUFFSIZE;
      }
      b >>= 1;
    }
  }
}
